// modes.h: a mode is its number (bits 0-14) plus an ANSI flag (bit 15). The
// header's helpers are `static inline`, so the library does not export them.

/// Packs a mode number and whether it is an ANSI mode (`ghostty_mode_new`, modes.h:115).
#[inline]
pub const fn ghostty_mode_new(value: u16, ansi: bool) -> GhosttyMode {
    (value & 0x7FFF) | ((ansi as u16) << 15)
}

/// The mode's number (`ghostty_mode_value`, modes.h:127).
#[inline]
pub const fn ghostty_mode_value(mode: GhosttyMode) -> u16 {
    mode & 0x7FFF
}

/// Whether the mode is an ANSI mode rather than a DEC private one (`ghostty_mode_ansi`, modes.h:139).
#[inline]
pub const fn ghostty_mode_ansi(mode: GhosttyMode) -> bool {
    (mode >> 15) != 0
}

macro_rules! modes {
    ($($(#[$doc:meta])* $name:ident = ($value:expr, $ansi:expr);)*) => {
        $($(#[$doc])* pub const $name: GhosttyMode = ghostty_mode_new($value, $ansi);)*
    };
}

