// types.h:551-561: sized structs.

/// `GHOSTTY_INIT_SIZED(type)` (types.h:551): a zeroed sized struct whose
/// `size` field holds its own size, which tells the library which version of
/// the struct the caller was built against.
///
/// ```
/// use libghostty_render_sys::*;
/// let cursor = ghostty_init_sized!(GhosttyRenderStateCursor);
/// assert_eq!(cursor.size, std::mem::size_of::<GhosttyRenderStateCursor>());
/// ```
#[macro_export]
macro_rules! ghostty_init_sized {
    ($ty:ty) => {{
        let mut value: $ty = ::core::default::Default::default();
        value.size = ::core::mem::size_of::<$ty>();
        value
    }};
}
