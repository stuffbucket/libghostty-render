// color.h:101-145: palette mask helpers.

/// The storage word for a palette index (`GHOSTTY_COLOR_PALETTE_MASK_WORD`, color.h:101).
#[inline]
pub const fn ghostty_color_palette_mask_word(index: u8) -> usize {
    (index >> 6) as usize
}

/// The storage bit for a palette index (`GHOSTTY_COLOR_PALETTE_MASK_BIT`, color.h:110).
#[inline]
pub const fn ghostty_color_palette_mask_bit(index: u8) -> u64 {
    1 << (index & 63)
}

/// Marks a palette index (`GHOSTTY_COLOR_PALETTE_MASK_SET`, color.h:120).
#[inline]
pub fn ghostty_color_palette_mask_set(mask: &mut GhosttyColorPaletteMask, index: u8) {
    mask.bits[ghostty_color_palette_mask_word(index)] |= ghostty_color_palette_mask_bit(index);
}

/// Clears a palette index (`GHOSTTY_COLOR_PALETTE_MASK_UNSET`, color.h:131).
#[inline]
pub fn ghostty_color_palette_mask_unset(mask: &mut GhosttyColorPaletteMask, index: u8) {
    mask.bits[ghostty_color_palette_mask_word(index)] &= !ghostty_color_palette_mask_bit(index);
}

/// Whether a palette index is marked (`GHOSTTY_COLOR_PALETTE_MASK_IS_SET`, color.h:143).
#[inline]
pub const fn ghostty_color_palette_mask_is_set(mask: &GhosttyColorPaletteMask, index: u8) -> bool {
    mask.bits[ghostty_color_palette_mask_word(index)] & ghostty_color_palette_mask_bit(index) != 0
}

