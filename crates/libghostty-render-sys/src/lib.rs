pub const GHOSTTY_STYLE_UNDERLINE_SHIFT: u32 = 8;
/// The bits of `GhosttyStyleFlags` holding the underline style, 8 to 10 (style.h:168).
pub const GHOSTTY_STYLE_UNDERLINE_MASK: GhosttyStyleFlags = 0x7 << GHOSTTY_STYLE_UNDERLINE_SHIFT;

/// The underline style of `style`, a `GHOSTTY_SGR_UNDERLINE_*` value; zero
/// (`GHOSTTY_SGR_UNDERLINE_NONE`) means none (`GHOSTTY_STYLE_UNDERLINE`, style.h:191).
#[inline]
pub const fn ghostty_style_underline(style: &GhosttyStyle) -> GhosttySgrUnderline {
    ((style.flags & GHOSTTY_STYLE_UNDERLINE_MASK) >> GHOSTTY_STYLE_UNDERLINE_SHIFT)
        as GhosttySgrUnderline
}

